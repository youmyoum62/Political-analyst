# 名簿上の短縮表記 → 会派の正式名称（衆参公式サイトで確認した一次情報のみ）。
# 「中道」は衆議院議員プロフィールで会派名「中道改革連合・無所属」と明記されており、
# 名簿一覧では「中道」に短縮表示されている（公明/立憲の誤りや列ズレではなく実在会派）。
PARTY_ALIASES: dict[str, str] = {
    "みら": "みらい",
    "無": "無所属",
    "中道": "中道改革連合・無所属",
}


def normalize_party(name: str | None) -> str:
    if not name or not name.strip():
        return "無所属"
    n = name.strip()
    return PARTY_ALIASES.get(n, n)
